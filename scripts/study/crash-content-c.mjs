// ───────────────────────────────────────────── Architecture & reliability
export const arch = S('arch', 'Architecture & Reliability', 10, [
  K('Arch 1/6 · Timeouts, retries, idempotency',
    L('**Every** network call has a timeout. No timeout = threads/sockets pile up during an outage.',
      '**Retry** only transient failures (5xx, timeouts, 429), with **exponential backoff + jitter** and a cap. Never retry blindly on a non-idempotent call.',
      '**Idempotency key:** the client sends a unique key; the server stores the result and returns it on a repeat, so retries are safe (payments, orders).',
      '**Retry budgets** stop retry storms: retries are limited to ~10% of traffic.'),
    C(`async function withRetry(fn, { tries = 4, base = 100 } = {}) {
  for (let i = 0; ; i++) {
    try { return await fn(); }
    catch (e) {
      if (i === tries - 1 || !isTransient(e)) throw e;
      const delay = Math.random() * base * 2 ** i;   // full jitter
      await new Promise((r) => setTimeout(r, delay));
    }
  }
}`),
  ),
  K('Arch 2/6 · Circuit breakers, bulkheads, fallbacks',
    CS.circuit,
    L('**Circuit breaker:** after N failures, fail fast for a cool-down, then let a few test requests through (half-open).',
      '**Bulkhead:** separate pools/limits per dependency so one slow service cannot eat all connections.',
      '**Fallbacks / graceful degradation:** serve cached or default data, hide the non-critical widget.',
      '**Load shedding:** reject early (429/503) when overloaded rather than slowing everyone down.'),
  ),
  K('Arch 3/6 · Async messaging patterns',
    T(['Pattern', 'Use it when'], [
      ['Queue (SQS, RabbitMQ)', 'one consumer group processes each job; buffer bursts; retries + dead-letter queue'],
      ['Pub/sub (SNS, EventBridge)', 'many independent subscribers react to one event'],
      ['Log / stream (Kafka, Kinesis)', 'ordered per partition, replayable, high throughput, many readers at their own pace'],
    ]),
    L('Delivery is **at-least-once** in practice: consumers must be **idempotent** (dedupe by message id).',
      'Ordering is only per partition / message group; choose the key (e.g. order id) deliberately.',
      'Poison messages go to a **DLQ** after N attempts, with an alarm.'),
    CS.outbox,
    P('**Transactional outbox:** write the business row and the event row in one DB transaction; a relay publishes the event. This avoids the "saved to DB but failed to publish" dual-write bug.'),
  ),
  K('Arch 4/6 · Distributed transactions: sagas',
    CS.saga,
    L('A **saga** is a sequence of local transactions; on failure, run **compensating actions** in reverse (refund, release stock).',
      '**Orchestration:** a coordinator (Step Functions, Temporal) drives steps. Easier to reason about.',
      '**Choreography:** services react to each other\'s events. Looser coupling, harder to trace.',
      'Avoid two-phase commit across services: it blocks and couples availability.'),
  ),
  K('Arch 5/6 · Architecture styles',
    T(['Style', 'Pros', 'Cons'], [
      ['Modular monolith', 'simple deploys, easy refactors, one DB transaction', 'one scaling unit; needs discipline on boundaries'],
      ['Microservices', 'independent deploys and scaling per team', 'network failures, distributed data, ops cost, tracing needed'],
      ['Event-driven', 'loose coupling, easy to add consumers', 'eventual consistency, harder debugging'],
      ['Serverless', 'no servers, scale to zero, pay per use', 'cold starts, limits, vendor coupling'],
      ['CQRS / event sourcing', 'separate optimised read models; full audit history', 'complexity; only where the domain needs it'],
    ]),
    CS.gatewayMesh,
  ),
  K('Arch 6/6 · Deploys and observability',
    CS.deploy,
    L('**Blue-green:** switch all traffic to a new stack; instant rollback. **Canary:** 1% → 10% → 100% with automatic rollback on error/latency alarms. **Rolling:** replace instances in batches.',
      '**Feature flags** separate deploy from release; kill switches for risky features.',
      '**Three pillars:** logs (what happened), metrics (how much/how fast), traces (where time went across services).',
      'Alert on **SLOs** (e.g. 99.9% of requests < 300 ms) and error budgets, using RED (rate, errors, duration) for services and USE (utilisation, saturation, errors) for resources.'),
  ),
  RAPID('Reliability rapid-fire', [
    ['SLI vs SLO vs SLA?', 'Indicator (measured), objective (internal target), agreement (contract with penalties).'],
    ['Thundering herd?', 'Many clients retry/refresh at once; fix with jitter, request coalescing, staggered TTLs.'],
    ['Cache stampede?', 'Hot key expires and everyone hits the DB; single-flight lock, early refresh, stale-while-revalidate.'],
    ['Back-pressure in systems?', 'Bounded queues + rejecting/slowing producers when consumers fall behind.'],
    ['Chaos engineering?', 'Inject failures deliberately (kill instances, add latency) to prove resilience.'],
    ['RTO vs RPO?', 'How long to recover vs how much data you can lose.'],
  ]),
  K('Arch · Go deeper', GO(['/system-design', 'System Design guide'], ['/interview-cheatsheet#architecture', 'Cheatsheet: Architecture & Reliability'])),
]);

